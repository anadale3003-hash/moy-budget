import {readFile} from 'node:fs/promises';
import assert from 'node:assert/strict';
const source=await readFile(new URL('./local-reminders.js',import.meta.url),'utf8');
const module={exports:{}};new Function('module',source)(module);
const {makeReminderPlan}=module.exports;
const now=new Date(2026,10,26,8),payday=(key,day)=>{const [y,m]=key.split('-').map(Number);const d=new Date(y,m-1,Math.min(day,new Date(y,m,0).getDate()));while([0,6].includes(d.getDay()))d.setDate(d.getDate()-1);return d;};
const base={now,mode:'all',frequency:'twice',days:{advance:16,salary:1},payday,receipts:[],bills:[{due:'2026-12-03',remaining:100},{due:'2026-12-04',remaining:0}],mortgage:{due:'2026-12-01',remaining:500},configured:true};
const p=makeReminderPlan(base);
const day=(n)=>n.schedule.at.getDate(),month=(n)=>n.schedule.at.getMonth();
assert(p.length>90);
assert.equal(new Set(p.map(n=>n.id)).size,p.length);
assert(p.every(n=>n.schedule.at>now&&!/\d{3}/.test(n.body)));
assert(p.some(n=>n.title.includes('День выплаты')&&day(n)===1&&month(n)===11&&n.body.includes('зарплаты')));
assert(p.some(n=>n.title.includes('Обязательные')&&day(n)===3&&month(n)===11));
assert(!p.some(n=>n.title.includes('Обязательные')&&day(n)===4&&month(n)===11));
assert(p.some(n=>n.title.includes('Время обновить')));
assert(p.some(n=>n.title.includes('Итоги месяца')));
assert.equal(makeReminderPlan({...base,mode:'none'}).length,0);
assert.equal(makeReminderPlan({...base,configured:false}).length,0);
const pay=makeReminderPlan({...base,mode:'pay'});
assert(pay.length>0&&pay.every(n=>n.title.includes('День выплаты')));
const confirmed=makeReminderPlan({...base,mode:'pay',receipts:[{id:'2026-11-salary',date:'2026-11-26'}]});
assert(!confirmed.some(n=>day(n)===1&&month(n)===11&&n.body.includes('зарплаты')));
const future=makeReminderPlan({...base,mode:'pay',receipts:[{id:'2026-11-salary',date:'2026-11-30'}]});
assert(future.some(n=>day(n)===1&&month(n)===11&&n.body.includes('зарплаты')));
const once=makeReminderPlan({...base,mode:'pay',frequency:'once'});
assert(once.every(n=>!n.body.includes('аванса')));
const paid=makeReminderPlan({...base,bills:[],mortgage:{due:'2026-12-01',remaining:0}});
assert(!paid.some(n=>n.title.includes('Обязательные')));
assert.deepEqual(makeReminderPlan(base).map(n=>n.id),p.map(n=>n.id));
console.log('16 local reminder planning assertions passed');
